const fs = require('node:fs');
const SUPPORT_BLOCK = `## Support the Project

<a href="https://ko-fi.com/paryx">
  <img src="https://storage.ko-fi.com/cdn/brandasset/v2/support_me_on_kofi_dark.png" alt="Support me on Ko-fi" height="44">
</a>`;

function prereleaseNotice(tag, repo) {
  const rc = tag.match(/-rc\.(\d+)/);
  if (rc) return `> [!TIP]\n> This is our release candidate version ${rc[1]}. It's mostly a stable build, so it should be safe for regular use, but please report any bugs you find at https://github.com/${repo}/issues.`;
  if (tag.includes('-beta')) return '> [!WARNING]\n> This is a beta release. It should be broadly stable, but you may run into occasional bugs. Please report anything unexpected.';
  if (tag.includes('-alpha')) return '> [!CAUTION]\n> This is an alpha release. It is unstable and may contain significant bugs, incomplete features, or data-loss risks. Use at your own risk and avoid production data.';
  return '';
}

function writeReleaseNotes() {
  const tag = process.env.RELEASE_TAG;
  if (!/^v\d+\.\d+\.\d+(?:-[0-9A-Za-z.-]+)?$/.test(tag)) throw new Error('Invalid release tag');
  const repo = process.env.GITHUB_REPOSITORY;
  if (!/^[\w.-]+\/[\w.-]+$/.test(repo)) throw new Error('Invalid repository');
  const readOptional = name => fs.existsSync(name) ? fs.readFileSync(name, 'utf8').trim() : '';
  const maintained = fs.existsSync('notes/changelog/release-notes.md') ? 'notes/changelog/release-notes.md' : 'notes/release-notes.md';
  const changelog = fs.readFileSync(maintained, 'utf8').trim();
  const generated = readOptional('notes/github/github-release-notes.md');
  const security = readOptional('notes/security/security.md');
  const checksums = fs.readFileSync('release/SHA256SUMS.txt', 'utf8').trim();
  const assets = fs.readdirSync('release').filter(name => name.endsWith('.exe')).sort();
  const rows = assets.map(name => {
    if (!/^roblox-manager-v.+?-windows-x64(?:-setup)?\.exe$/.test(name)) throw new Error(`Unexpected release download: ${name}`);
    const description = 'For a normal Intel or AMD Windows PC - ' + (name.endsWith('-setup.exe') ? 'installer' : 'portable app (requires WebView2 Runtime)');
    return `| [\`${name}\`](https://github.com/${repo}/releases/download/${tag}/${name}) | ${description} |`;
  });
  const downloads = ['<details>', '<summary>Which download do I want?</summary>', '', '| File | Use case |', '| --- | --- |', ...rows, '', '</details>'].join('\n');
  const githubNotes = generated ? [
    '> [!NOTE]',
    `> The section below may be inaccurate, as it's auto-generated by GitHub Actions. See [CHANGELOG.md](https://github.com/${repo}/blob/main/CHANGELOG.md) for the maintained changelog.`,
    '', '<details>', '<summary>GitHub-generated notes</summary>', '', generated, '', '</details>',
  ].join('\n') : '';
  const sha256 = ['## SHA256', '', 'Checksums for all executable files and COMMIT.txt included in this release.', '', ...checksums.split(/\r?\n/).map(line => `- \`${line}\``)].join('\n');
  const parts = [
    changelog, downloads, githubNotes, sha256, security,
    prereleaseNotice(tag, repo), SUPPORT_BLOCK,
  ];
  fs.writeFileSync('final-release-notes.md', parts.filter(Boolean).join('\n\n'));
}

if (require.main === module) writeReleaseNotes();
module.exports = { SUPPORT_BLOCK, prereleaseNotice, writeReleaseNotes };
